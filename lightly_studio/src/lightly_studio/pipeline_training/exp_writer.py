"""Writes a YOLOX exp file from a TrainConfig, in the shape of the hand-written recipes."""

from __future__ import annotations

from pathlib import Path

from lightly_studio.pipeline_training.config import TrainConfig

# The sub folder of the run folder where YOLOX writes checkpoints and its own log.
TRAIN_OUTPUT_NAME = "train"

_TEMPLATE = '''"""Generated by LightlyStudio for the run folder it lives in. Do not edit."""
import os

import torch
from yolox.exp import Exp as MyExp

GPU_MEM_CAP_GB = {gpu_cap!r}


class Exp(MyExp):
    def __init__(self):
        super(Exp, self).__init__()
        if GPU_MEM_CAP_GB is not None and torch.cuda.is_available():
            total = torch.cuda.get_device_properties(0).total_memory / 2**30
            torch.cuda.set_per_process_memory_fraction(min(1.0, GPU_MEM_CAP_GB / total), 0)

        self.exp_name = {exp_name!r}
        self.output_dir = {output_dir!r}
        self.seed = {c.seed!r}

        # ---- model ----
        self.depth = {c.depth!r}
        self.width = {c.width!r}
        self.act = {c.act!r}
        self.num_classes = {num_classes!r}

        # ---- data ----
        self.data_dir = {data_dir!r}
        self.train_ann = "instances_train2017.json"
        self.val_ann = "instances_val2017.json"
        self.data_num_workers = {c.data_num_workers!r}

        # ---- resolution ----
        self.input_size = ({c.input_size!r}, {c.input_size!r})
        self.test_size = ({c.test_size!r}, {c.test_size!r})
        self.multiscale_range = {c.multiscale_range!r}

        # ---- schedule ----
        self.max_epoch = {c.max_epoch!r}
        self.warmup_epochs = {c.warmup_epochs!r}
        self.no_aug_epochs = {c.no_aug_epochs!r}
        self.basic_lr_per_img = {c.basic_lr_per_img!r}
        self.warmup_lr = {c.warmup_lr!r}
        self.scheduler = {c.scheduler!r}
        self.min_lr_ratio = {c.min_lr_ratio!r}
        self.ema = {c.ema!r}
        self.weight_decay = {c.weight_decay!r}
        self.momentum = {c.momentum!r}

        # ---- augmentation ----
        self.mosaic_prob = {c.mosaic_prob!r}
        self.mixup_prob = {c.mixup_prob!r}
        self.hsv_prob = {c.hsv_prob!r}
        self.flip_prob = {c.flip_prob!r}
        self.degrees = {c.degrees!r}
        self.translate = {c.translate!r}
        self.mosaic_scale = ({c.mosaic_scale_min!r}, {c.mosaic_scale_max!r})
        self.mixup_scale = ({c.mixup_scale_min!r}, {c.mixup_scale_max!r})
        self.shear = {c.shear!r}
        self.enable_mixup = {c.enable_mixup!r}

        # ---- eval / logging ----
        self.eval_interval = {c.eval_interval!r}
        self.print_interval = {c.print_interval!r}
        self.save_history_ckpt = {c.save_history_ckpt!r}
        self.test_conf = {c.test_conf!r}
        self.nmsthre = {c.nmsthre!r}

    def get_dataset(self, cache: bool = False, cache_type: str = "ram"):
        from yolox.data import COCODataset, TrainTransform

        return COCODataset(
            data_dir=self.data_dir,
            json_file=self.train_ann,
            name="train2017",
            img_size=self.input_size,
            preproc=TrainTransform(
                max_labels={c.max_labels!r}, flip_prob=self.flip_prob, hsv_prob=self.hsv_prob
            ),
            cache=cache,
            cache_type=cache_type,
        )

    def get_eval_dataset(self, **kwargs):
        from yolox.data import COCODataset, ValTransform

        return COCODataset(
            data_dir=self.data_dir,
            json_file=self.val_ann,
            name="val2017",
            img_size=self.test_size,
            preproc=ValTransform(legacy=kwargs.get("legacy", False)),
        )
'''


def render_exp(config: TrainConfig, data_dir: Path, num_classes: int, output_dir: Path) -> str:
    """Returns the exp file source for one run.

    Args:
        config: The user's settings.
        data_dir: The COCO dataset folder with train2017/, val2017/ and annotations/.
        num_classes: Number of classes in the dataset.
        output_dir: Where YOLOX writes checkpoints; the run folder.
    """
    return _TEMPLATE.format(
        c=config,
        gpu_cap=config.gpu_memory_cap_gb,
        exp_name=TRAIN_OUTPUT_NAME,
        output_dir=str(output_dir),
        num_classes=num_classes,
        data_dir=str(data_dir),
    )
